int main() {
    int a[2][3];
    int b[2][3];
    int c[2][3];

    a[0][0] = 1; a[0][1] = 2; a[0][2] = 3;
    a[1][0] = 4; a[1][1] = 5; a[1][2] = 6;

    b[0][0] = 7; b[0][1] = 8; b[0][2] = 9;
    b[1][0] = 1; b[1][1] = 2; b[1][2] = 3;

    int i = 0;
    while (i < 2) {
        int j = 0;
        while (j < 3) {
            c[i][j] = a[i][j] + b[i][j];
            j = j + 1;
        }
        i = i + 1;
    }
    return 0;
}
